const toggle=document.querySelector('.menu-toggle');
const nav=document.querySelector('.nav');
const langSelect=document.querySelector('.lang-select');
const supported=['fr','en','de','it'];

const detectLanguage=()=>{
  const stored=localStorage.getItem('remaprohub-language');
  if(supported.includes(stored)) return stored;
  const browser=(navigator.languages?.[0]||navigator.language||'fr').toLowerCase().slice(0,2);
  return supported.includes(browser)?browser:'fr';
};

let currentLang=detectLanguage();

function menuLabel(open){
  const labels={
    fr:open?'Fermer le menu':'Ouvrir le menu',
    en:open?'Close menu':'Open menu',
    de:open?'Menü schließen':'Menü öffnen',
    it:open?'Chiudi menu':'Apri menu'
  };
  return labels[currentLang]||labels.fr;
}

function applyLanguage(lang){
  currentLang=supported.includes(lang)?lang:'fr';
  const dict=translations[currentLang];
  document.documentElement.lang=currentLang;
  document.title=dict.pageTitle;
  const description=document.querySelector('meta[name="description"]');
  if(description) description.setAttribute('content',dict.metaDescription);
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key=el.dataset.i18n;
    if(dict[key]!==undefined) el.textContent=dict[key];
  });
  if(langSelect) langSelect.value=currentLang;
  if(toggle) toggle.setAttribute('aria-label',menuLabel(toggle.getAttribute('aria-expanded')==='true'));
  localStorage.setItem('remaprohub-language',currentLang);
}

langSelect?.addEventListener('change',e=>applyLanguage(e.target.value));

if(toggle&&nav){
  const closeMenu=()=>{
    nav.classList.remove('open');
    toggle.setAttribute('aria-expanded','false');
    toggle.setAttribute('aria-label',menuLabel(false));
  };
  toggle.addEventListener('click',()=>{
    const open=nav.classList.toggle('open');
    toggle.setAttribute('aria-expanded',String(open));
    toggle.setAttribute('aria-label',menuLabel(open));
  });
  nav.querySelectorAll('a').forEach(a=>a.addEventListener('click',closeMenu));
  document.addEventListener('keydown',e=>{if(e.key==='Escape') closeMenu()});
  document.addEventListener('click',e=>{
    if(nav.classList.contains('open')&&!nav.contains(e.target)&&!toggle.contains(e.target)&&!e.target.closest('.lang-picker')) closeMenu();
  });
}

applyLanguage(currentLang);
