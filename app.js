const toggle=document.querySelector('.menu-toggle');
const nav=document.querySelector('.nav');
const langToggle=document.querySelector('.lang-toggle');

const getStoredLanguage=()=>{
  const stored=localStorage.getItem('remaprohub-language');
  if(stored==='fr'||stored==='en') return stored;
  return navigator.language&&navigator.language.toLowerCase().startsWith('en')?'en':'fr';
};

let currentLang=getStoredLanguage();

function applyLanguage(lang){
  currentLang=translations[lang]?lang:'fr';
  const dict=translations[currentLang];
  document.documentElement.lang=currentLang;
  document.title=dict.pageTitle;
  const description=document.querySelector('meta[name="description"]');
  if(description) description.setAttribute('content',dict.metaDescription);
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key=el.dataset.i18n;
    if(dict[key]!==undefined) el.textContent=dict[key];
  });
  if(langToggle){
    langToggle.textContent=currentLang==='fr'?'EN':'FR';
    langToggle.setAttribute('aria-label',currentLang==='fr'?'Switch to English':'Passer en français');
    langToggle.setAttribute('title',currentLang==='fr'?'English':'Français');
  }
  if(toggle){
    const open=toggle.getAttribute('aria-expanded')==='true';
    toggle.setAttribute('aria-label',currentLang==='fr'?(open?'Fermer le menu':'Ouvrir le menu'):(open?'Close menu':'Open menu'));
    const label=toggle.querySelector('.menu-label');
    if(label) label.textContent=currentLang==='fr'?'Menu':'Menu';
  }
  localStorage.setItem('remaprohub-language',currentLang);
}

if(langToggle){
  langToggle.addEventListener('click',()=>applyLanguage(currentLang==='fr'?'en':'fr'));
}

if(toggle&&nav){
  const closeMenu=()=>{
    nav.classList.remove('open');
    toggle.setAttribute('aria-expanded','false');
    toggle.setAttribute('aria-label',currentLang==='fr'?'Ouvrir le menu':'Open menu');
  };

  toggle.addEventListener('click',()=>{
    const open=nav.classList.toggle('open');
    toggle.setAttribute('aria-expanded',String(open));
    toggle.setAttribute('aria-label',currentLang==='fr'?(open?'Fermer le menu':'Ouvrir le menu'):(open?'Close menu':'Open menu'));
  });

  nav.querySelectorAll('a').forEach(a=>a.addEventListener('click',closeMenu));

  document.addEventListener('keydown',e=>{
    if(e.key==='Escape') closeMenu();
  });

  document.addEventListener('click',e=>{
    if(nav.classList.contains('open')&&!nav.contains(e.target)&&!toggle.contains(e.target)&&(!langToggle||!langToggle.contains(e.target))) closeMenu();
  });
}

applyLanguage(currentLang);
