import assert from 'node:assert/strict';
import {normalizeMenuScanItems,classifyMenuScanDuplicates,applyMenuScanRows,renderMenuScanPanel,MENU_SCAN_MAX_PHOTOS} from '../src/menu-scan.js';
assert.equal(MENU_SCAN_MAX_PHOTOS,4);
const raw=normalizeMenuScanItems([{name:'Entrecôte',category:'Viandes',price:'34,50',confidence:.92,type:'dish'},{name:'Burger',price:null},{name:'',price:13}]);
assert.equal(raw.length,2);
assert.equal(raw[0].price,34.5);
assert.equal(raw[1].price,null);
const doc={pages:[],categories:[],buttons:[]};
const classified=classifyMenuScanDuplicates(raw,doc);
assert.deepEqual(classified.map(x=>x.mode),['create','create']);
const applied=applyMenuScanRows(doc,classified);
assert.equal(applied.created,1,'missing price must not be treated as free');
assert.equal(doc.pages[0].name,'Caisse');
assert.equal(doc.categories[0].name,'Viandes');
assert.equal(doc.buttons[0].item.price,34.5);
assert.equal(doc.buttons[0].station,'kitchen');
const duplicate=classifyMenuScanDuplicates(normalizeMenuScanItems([{name:'Entrecote',price:40}]),doc);
assert.equal(duplicate[0].mode,'skip');
assert.equal(applyMenuScanRows(doc,duplicate).created,0);
assert.equal(doc.buttons.length,1);
assert.equal(applyMenuScanRows(doc,[{...duplicate[0],mode:'update'}]).updated,1);
assert.equal(doc.buttons[0].item.price,40);
doc.buttons[0].productId='hub-1';
assert.equal(applyMenuScanRows(doc,[{...duplicate[0],mode:'update',price:80}]).updated,0);
assert.equal(doc.buttons[0].item.price,40);
const drinks={pages:[],categories:[],buttons:[]};
const two=applyMenuScanRows(drinks,[{name:'Coca',category:'Boissons',price:4,type:'drink',mode:'create'}, {name:'coca',category:'Boissons',price:7,mode:'create'}],{taxRate:2.6});
assert.equal(two.created,1);
assert.equal(drinks.buttons[0].station,'bar');
assert.equal(drinks.buttons[0].item.taxRate,2.6);
assert.match(renderMenuScanPanel('',drinks),/Scan Menu IA/);
assert.throws(()=>applyMenuScanRows(drinks,[{name:'x',price:10,mode:'create'}],{taxRate:-1}),/TVA_INVALIDE/);
console.log('menu-scan.test.mjs OK');
