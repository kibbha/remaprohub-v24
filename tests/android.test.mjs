import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const workflow=readFileSync('.github/workflows/android.yml','utf8');
const activity=readFileSync('android-native/MainActivity.java','utf8');
const launcher=readFileSync('android-native/ic_launcher.xml','utf8');
const roundLauncher=readFileSync('android-native/ic_launcher_round.xml','utf8');
const launcherColors=readFileSync('android-native/remaprohub_colors.xml','utf8');
