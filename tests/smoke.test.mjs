import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const pkg=JSON.parse(read('package.json'));
assert.equal(pkg.version,'0.17.0');
const app=read('src/app.js'),cloud=read('src/cloud.js');
for(const token of ['operatorLoginView','operator_login','operator_current','teamView','switchOperator','operatorRequired'])assert.ok(app.includes(token),token);
for(const token of ['OPERATOR_KEY','currentOperatorSession','operatorSessionToken'])assert.ok(cloud.includes(token),token);
assert.doesNotMatch(cloud,/service[_-]?role/i);
console.log('ReMaPro POS 0.17 smoke checks passed');
