import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const pkg=JSON.parse(read('package.json'));
assert.equal(pkg.version,'0.25.2');
assert.ok(read('src/app.js').includes("APP_VERSION='0.25.2'"));
assert.equal(JSON.parse(read('capacitor.config.json')).webDir,'app');
const db=read('src/db.js'),printer=read('src/printer.js'),cloud=read('src/cloud.js');
assert.ok(db.includes('CapacitorSQLite'));
assert.ok(db.includes('createConnection'));
assert.ok(printer.includes('EscPosPrinter'));
assert.ok(printer.includes('createPrinter'));
assert.doesNotMatch(db,/import\s*\(\s*['"]@/);
assert.doesNotMatch(printer,/import\s*\(\s*['"]@/);
assert.doesNotMatch(cloud,/service[_-]?role/i);
const inject=read('scripts/inject-runtime-config.mjs'),runtime=read('runtime-config.js');
assert.ok(inject.includes('DEFAULT_SUPABASE_PUBLISHABLE_KEY'));
assert.ok(runtime.includes('sb_publishable_'));
assert.doesNotMatch(runtime,/service[_-]?role|sb_secret_/i);
assert.ok(read('sw.js').includes('remapro-pos-shell-v0252'));
assert.ok(read('sw.js').includes('./src/printer.js'));
console.log('ReMaPro POS 0.25.2 native bridge checks passed');
