import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const pkg=JSON.parse(read('package.json'));
assert.equal(pkg.name,'remapro-pos');
assert.equal(pkg.version,'0.3.0');
const cap=JSON.parse(read('capacitor.config.json'));
assert.equal(cap.appId,'com.remapro.pos');
const app=read('src/app.js');
for(const token of ['open_cash_session','commit_order','close_cash_session','quick-item','refresh-catalog','catalog_item_id:x.quick?null:x.id'])assert.ok(app.includes(token),token);
const cloud=read('src/cloud.js');
assert.match(cloud,/remapro-pos-sync/);
assert.doesNotMatch(cloud,/service[_-]?role/i);
assert.doesNotMatch(read('runtime-config.js'),/sb_secret_|eyJ[A-Za-z0-9_-]{20,}/);
console.log('ReMaPro POS 0.3 smoke checks passed');
