import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
assert.equal(JSON.parse(read('package.json')).version,'0.8.0');
assert.equal(JSON.parse(read('capacitor.config.json')).appId,'com.remapro.pos');
const app=read('src/app.js');
for(const token of ['printReceipt','printProductionOrder','data-print-receipt','data-print-production','printHtml'])assert.ok(app.includes(token),token);
const css=read('src/styles.css');
assert.match(css,/@media print/);
assert.match(css,/80mm/);
assert.doesNotMatch(read('src/cloud.js'),/service[_-]?role/i);
console.log('ReMaPro POS 0.8 smoke checks passed');
