import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const pkg=JSON.parse(read('package.json'));
assert.equal(pkg.version,'0.20.0');
const app=read('src/app.js');
for(const token of ['list_provider_connections','providerConnections','providerStatusLabel','Terminal API Cloud','Terminal / PSP'])assert.ok(app.includes(token),token);
assert.ok(app.includes("paymentProviders===true"));
assert.ok(app.includes("confirmation sur un terminal externe"));
assert.ok(read('src/db.js').includes('SQLiteConnection'));
assert.ok(read('src/printer.js').includes('BluetoothPrinter'));
assert.doesNotMatch(read('src/cloud.js'),/service[_-]?role/i);
console.log('ReMaPro POS 0.20 smoke checks passed');
