import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const pkg=JSON.parse(read('package.json'));
assert.equal(pkg.version,'0.4.0');
assert.equal(JSON.parse(read('capacitor.config.json')).appId,'com.remapro.pos');
const app=read('src/app.js');
for(const token of ['list_tables','list_open_orders','save_open_order','settle_open_order','data-table','save-open-order','OPEN'])assert.ok(app.includes(token),token);
const cloud=read('src/cloud.js');
assert.match(cloud,/remapro-pos-sync/);
assert.doesNotMatch(cloud,/service[_-]?role/i);
console.log('ReMaPro POS 0.4 smoke checks passed');
